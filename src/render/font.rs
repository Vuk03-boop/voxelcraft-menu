pub const GLYPH_W: u32 = 3;
pub const GLYPH_H: u32 = 5;
pub const CELL_W: u32 = 4;
pub const CELL_H: u32 = 6;
pub const FIRST: u8 = 32;
pub const COUNT: u32 = 96;

const fn g(rows: [&'static str; 5]) -> [&'static str; 5] {
    rows
}

fn glyph(c: u8) -> [&'static str; 5] {
    match c as char {
        'A' => g(["###", "#.#", "###", "#.#", "#.#"]),
        'B' => g(["##.", "#.#", "##.", "#.#", "##."]),
        'C' => g(["###", "#..", "#..", "#..", "###"]),
        'D' => g(["##.", "#.#", "#.#", "#.#", "##."]),
        'E' => g(["###", "#..", "##.", "#..", "###"]),
        'F' => g(["###", "#..", "##.", "#..", "#.."]),
        'G' => g(["###", "#..", "#.#", "#.#", "###"]),
        'H' => g(["#.#", "#.#", "###", "#.#", "#.#"]),
        'I' => g(["###", ".#.", ".#.", ".#.", "###"]),
        'J' => g(["..#", "..#", "..#", "#.#", "###"]),
        'K' => g(["#.#", "#.#", "##.", "#.#", "#.#"]),
        'L' => g(["#..", "#..", "#..", "#..", "###"]),
        'M' => g(["#.#", "###", "###", "#.#", "#.#"]),
        'N' => g(["##.", "#.#", "#.#", "#.#", "#.#"]),
        'O' => g(["###", "#.#", "#.#", "#.#", "###"]),
        'P' => g(["###", "#.#", "###", "#..", "#.."]),
        'Q' => g(["###", "#.#", "#.#", "###", "..#"]),
        'R' => g(["###", "#.#", "##.", "#.#", "#.#"]),
        'S' => g(["###", "#..", "###", "..#", "###"]),
        'T' => g(["###", ".#.", ".#.", ".#.", ".#."]),
        'U' => g(["#.#", "#.#", "#.#", "#.#", "###"]),
        'V' => g(["#.#", "#.#", "#.#", "#.#", ".#."]),
        'W' => g(["#.#", "#.#", "###", "###", "#.#"]),
        'X' => g(["#.#", "#.#", ".#.", "#.#", "#.#"]),
        'Y' => g(["#.#", "#.#", ".#.", ".#.", ".#."]),
        'Z' => g(["###", "..#", ".#.", "#..", "###"]),
        '0' => g(["###", "#.#", "#.#", "#.#", "###"]),
        '1' => g([".#.", "##.", ".#.", ".#.", "###"]),
        '2' => g(["###", "..#", "###", "#..", "###"]),
        '3' => g(["###", "..#", "###", "..#", "###"]),
        '4' => g(["#.#", "#.#", "###", "..#", "..#"]),
        '5' => g(["###", "#..", "###", "..#", "###"]),
        '6' => g(["###", "#..", "###", "#.#", "###"]),
        '7' => g(["###", "..#", "..#", "..#", "..#"]),
        '8' => g(["###", "#.#", "###", "#.#", "###"]),
        '9' => g(["###", "#.#", "###", "..#", "###"]),
        '.' => g(["...", "...", "...", "...", ".#."]),
        ',' => g(["...", "...", "...", ".#.", "#.."]),
        ':' => g(["...", ".#.", "...", ".#.", "..."]),
        '-' => g(["...", "...", "###", "...", "..."]),
        '+' => g(["...", ".#.", "###", ".#.", "..."]),
        '/' => g(["..#", "..#", ".#.", "#..", "#.."]),
        '%' => g(["#.#", "..#", ".#.", "#..", "#.#"]),
        '(' => g([".#.", "#..", "#..", "#..", ".#."]),
        ')' => g([".#.", "..#", "..#", "..#", ".#."]),
        '=' => g(["...", "###", "...", "###", "..."]),
        '<' => g(["..#", ".#.", "#..", ".#.", "..#"]),
        '>' => g(["#..", ".#.", "..#", ".#.", "#.."]),
        '_' => g(["...", "...", "...", "...", "###"]),
        '!' => g([".#.", ".#.", ".#.", "...", ".#."]),
        '?' => g(["###", "..#", ".##", "...", ".#."]),
        '#' => g(["#.#", "###", "#.#", "###", "#.#"]),
        '*' => g(["#.#", ".#.", "###", ".#.", "#.#"]),
        '[' => g(["##.", "#..", "#..", "#..", "##."]),
        ']' => g([".##", "..#", "..#", "..#", ".##"]),
        '|' => g([".#.", ".#.", ".#.", ".#.", ".#."]),
        _ => g(["...", "...", "...", "...", "..."]),
    }
}

pub fn build_font_texture() -> (Vec<u8>, u32, u32) {
    let w = COUNT * CELL_W;
    let h = CELL_H;
    let mut v = vec![0u8; (w * h) as usize];
    for i in 0..COUNT {
        let rows = glyph(FIRST + i as u8);
        for (ry, row) in rows.iter().enumerate() {
            for (rx, ch) in row.bytes().enumerate() {
                if ch == b'#' {
                    let x = i * CELL_W + rx as u32;
                    let y = ry as u32;
                    v[(y * w + x) as usize] = 255;
                }
            }
        }
    }
    (v, w, h)
}
